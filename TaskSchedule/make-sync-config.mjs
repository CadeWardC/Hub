// Writes TaskSchedule/sync-config.js: the Directus sync token, encrypted with a
// passphrase, so the deployed app can sync after you type the passphrase once
// per device. Safe to commit — only the encrypted token goes in the file.
//
//   node TaskSchedule/make-sync-config.mjs
//
// Reads from the repo-root .env (or the environment):
//   DIRECTUS_URL             e.g. https://api.opcw032522.uk
//   DIRECTUS_SYNC_TOKEN      static token of the limited sync user
//   TASKSCHEDULE_PASSPHRASE  what you type in the app to unlock sync
//   DIRECTUS_COLLECTION      optional, defaults to taskschedule_items
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { webcrypto as crypto } from "node:crypto";

const here = dirname(fileURLToPath(import.meta.url));
try {
  for (const line of readFileSync(join(here, "..", ".env"), "utf8").split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
    if (m && !(m[1] in process.env)) process.env[m[1]] = m[2].replace(/^["']|["']$/g, "");
  }
} catch { /* no .env */ }

const url = (process.env.DIRECTUS_URL || "").replace(/\/+$/, "");
const token = process.env.DIRECTUS_SYNC_TOKEN;
const passphrase = process.env.TASKSCHEDULE_PASSPHRASE;
const collection = process.env.DIRECTUS_COLLECTION || "taskschedule_items";
if (!url || !token || !passphrase) {
  console.error("Set DIRECTUS_URL, DIRECTUS_SYNC_TOKEN and TASKSCHEDULE_PASSPHRASE in the repo-root .env.");
  process.exit(1);
}

// Must match normalise() in sync.js: case and extra spaces don't matter.
const normalise = (s) => s.trim().toLowerCase().replace(/\s+/g, " ");
const ITERATIONS = 600000;
const b64 = (buf) => Buffer.from(buf).toString("base64");

const salt = crypto.getRandomValues(new Uint8Array(16));
const iv = crypto.getRandomValues(new Uint8Array(12));
const base = await crypto.subtle.importKey("raw", new TextEncoder().encode(normalise(passphrase)), "PBKDF2", false, ["deriveKey"]);
const key = await crypto.subtle.deriveKey(
  { name: "PBKDF2", hash: "SHA-256", salt, iterations: ITERATIONS },
  base, { name: "AES-GCM", length: 256 }, false, ["encrypt"],
);
const sealed = await crypto.subtle.encrypt({ name: "AES-GCM", iv }, key, new TextEncoder().encode(token));

const config = { url, collection, iterations: ITERATIONS, salt: b64(salt), iv: b64(iv), token: b64(sealed) };
writeFileSync(join(here, "sync-config.js"),
  "// Generated by make-sync-config.mjs. The token is AES-GCM encrypted with the sync passphrase.\n" +
  `window.TASKSCHEDULE_SYNC = ${JSON.stringify(config, null, 2)};\n`);
console.log(`Wrote TaskSchedule/sync-config.js for ${url} (${collection}). Commit it and push to deploy.`);
