// Creates the Directus collection that Task & Schedule syncs to.
//
//   DIRECTUS_URL=https://your-directus DIRECTUS_ADMIN_TOKEN=... node TaskSchedule/directus-setup.mjs
//
// Both values can also live in the repo-root .env (never commit it). The admin
// token is only used here, from your machine; the app itself gets a separate,
// limited token (see DIRECTUS.md).
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const envFile = join(dirname(fileURLToPath(import.meta.url)), "..", ".env");
try {
  for (const line of readFileSync(envFile, "utf8").split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
    if (m && !(m[1] in process.env)) process.env[m[1]] = m[2].replace(/^["']|["']$/g, "");
  }
} catch { /* no .env */ }

const url = (process.env.DIRECTUS_URL || "").replace(/\/+$/, "");
const token = process.env.DIRECTUS_ADMIN_TOKEN;
const collection = process.env.DIRECTUS_COLLECTION || "taskschedule_items";
if (!url || !token) {
  console.error("Set DIRECTUS_URL and DIRECTUS_ADMIN_TOKEN (environment or repo-root .env).");
  process.exit(1);
}

async function api(path, method = "GET", body) {
  const res = await fetch(url + path, {
    method,
    headers: { Authorization: `Bearer ${token}`, "Content-Type": "application/json" },
    body: body ? JSON.stringify(body) : undefined,
  });
  const json = res.status === 204 ? null : await res.json().catch(() => null);
  if (!res.ok) {
    const err = new Error(json?.errors?.[0]?.message || `${res.status} ${res.statusText}`);
    err.status = res.status;
    throw err;
  }
  return json;
}

const FIELDS = [
  {
    field: "id", type: "string",
    meta: { interface: "input", readonly: true, note: "Item id generated by the app" },
    schema: { is_primary_key: true, has_auto_increment: false, max_length: 64 },
  },
  {
    field: "kind", type: "string",
    meta: {
      interface: "select-dropdown", width: "half",
      options: { choices: [{ text: "Task", value: "task" }, { text: "Event", value: "event" }, { text: "Protocol", value: "protocol" }] },
    },
    schema: { is_nullable: false, max_length: 16 },
  },
  {
    field: "data", type: "json",
    meta: { interface: "input-code", options: { language: "json" }, note: "The full task / event / protocol" },
    schema: { is_nullable: true },
  },
  {
    field: "updated", type: "bigInteger",
    meta: { interface: "input", width: "half", note: "Last change, milliseconds since 1970 (newest wins)" },
    schema: { is_nullable: false, default_value: 0 },
  },
  {
    field: "deleted", type: "boolean",
    meta: { interface: "boolean", width: "half", note: "Kept so every device learns about deletions" },
    schema: { default_value: false },
  },
];

let exists = true;
try {
  await api(`/collections/${collection}`);
} catch (e) {
  if (e.status !== 403 && e.status !== 404) throw e;
  exists = false;
}

if (!exists) {
  await api("/collections", "POST", {
    collection,
    meta: { icon: "checklist", note: "Task & Schedule app sync" },
    schema: {},
    fields: FIELDS,
  });
  console.log(`Created collection "${collection}".`);
} else {
  const have = new Set((await api(`/fields/${collection}`)).data.map((f) => f.field));
  const missing = FIELDS.filter((f) => !have.has(f.field));
  for (const f of missing) await api(`/fields/${collection}`, "POST", f);
  console.log(missing.length
    ? `Collection "${collection}" existed; added fields: ${missing.map((f) => f.field).join(", ")}.`
    : `Collection "${collection}" already set up.`);
}
console.log("Next: give a sync user access and a static token. See TaskSchedule/DIRECTUS.md.");
