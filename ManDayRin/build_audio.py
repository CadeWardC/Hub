"""Record ManDayRin's course audio with Microsoft neural voices (edge-tts).

Usage (needs Node and `pip install edge-tts`):
    python ManDayRin/build_audio.py

Reads weeks.js and writes, for every written week, two packs of concatenated MP3 clips:
    audio/week-NN-words.<hash>.bin   theme name + the 15 words (loaded by the Words tab for every unlocked week)
    audio/week-NN-lines.<hash>.bin   example sentences, pattern examples and scenario lines
plus audio/index.js (window.MANDAYRIN_AUDIO) mapping clip keys to byte ranges. Clip keys:
    t = theme, w<i> = word, x<i> = word example, p<i> = pattern example, s<scenario>-<line> = scenario line.
Each scenario character has their own voice. Clips are cached in .audio-cache/ so a rebuild only
records new or changed text. Pack names carry a content hash, so the service worker can cache them forever.
"""
import asyncio
import hashlib
import json
import pathlib
import subprocess

import edge_tts

ROOT = pathlib.Path(__file__).resolve().parent
AUDIO_DIR = ROOT / "audio"
CACHE_DIR = ROOT / ".audio-cache"

# (voice, rate, pitch)
NARRATOR = ("zh-CN-XiaoxiaoNeural", "-15%", "+0Hz")
CAST_VOICES = {
    "王芳": ("zh-CN-XiaoxiaoNeural", "-5%", "+0Hz"),
    "大卫": ("zh-CN-YunxiNeural", "-5%", "+0Hz"),
    "李明": ("zh-CN-YunjianNeural", "-5%", "+0Hz"),
    "安娜": ("zh-CN-XiaoyiNeural", "-5%", "+0Hz"),
    "林美": ("zh-CN-XiaoyiNeural", "-5%", "-5Hz"),
    "小美": ("zh-CN-XiaoyiNeural", "-5%", "+20Hz"),
    "李明的妈妈": ("zh-CN-XiaoxiaoNeural", "-10%", "-12Hz"),
    "服务员": ("zh-CN-YunyangNeural", "-5%", "+0Hz"),
}
DEFAULT_CAST_VOICE = ("zh-CN-YunyangNeural", "-5%", "+0Hz")
CONCURRENCY = 6


def load_course():
    script = (
        "global.window = {}; require(process.argv[1]);"
        "process.stdout.write(JSON.stringify(window.MANDAYRIN_COURSE));"
    )
    output = subprocess.run(["node", "-e", script, str(ROOT / "weeks.js")], check=True, capture_output=True, encoding="utf-8").stdout
    return json.loads(output)


def week_clips(week, data, theme):
    words = [("t", theme[1], NARRATOR)]
    lines = []
    for index, word in enumerate(data["words"]):
        words.append((f"w{index}", word[0], NARRATOR))
        lines.append((f"x{index}", word[4], NARRATOR))
    for index, pattern in enumerate(data["patterns"]):
        lines.append((f"p{index}", pattern[3], NARRATOR))
    for s_index, scenario in enumerate(data["scenarios"]):
        for l_index, (who, zh, _py, _en) in enumerate(scenario["lines"]):
            voice = CAST_VOICES.get(scenario["cast"][who][0], DEFAULT_CAST_VOICE)
            lines.append((f"s{s_index}-{l_index}", zh, voice))
    return {"words": words, "lines": lines}


def cache_path(text, voice):
    digest = hashlib.sha1(json.dumps([text, *voice], ensure_ascii=False).encode("utf-8")).hexdigest()[:20]
    return CACHE_DIR / f"{digest}.mp3"


async def record(text, voice, semaphore):
    path = cache_path(text, voice)
    if path.exists() and path.stat().st_size > 0:
        return path.read_bytes()
    name, rate, pitch = voice
    async with semaphore:
        for attempt in range(4):
            try:
                await edge_tts.Communicate(text, name, rate=rate, pitch=pitch).save(str(path))
                if path.stat().st_size > 0:
                    print(f"  recorded {text}")
                    return path.read_bytes()
            except Exception as error:  # network hiccups: retry
                print(f"  retry {attempt + 1} for {text}: {error}")
            await asyncio.sleep(1 + attempt * 2)
    raise RuntimeError(f"Could not record {text!r}")


async def main():
    course = load_course()
    AUDIO_DIR.mkdir(exist_ok=True)
    CACHE_DIR.mkdir(exist_ok=True)
    semaphore = asyncio.Semaphore(CONCURRENCY)
    index = {}
    keep = set()
    for week_key in sorted(course["weeks"], key=int):
        week = int(week_key)
        print(f"Week {week}")
        parts = week_clips(week, course["weeks"][week_key], course["themes"][week - 1])
        index[week] = {}
        for part, clips in parts.items():
            recordings = await asyncio.gather(*(record(text, voice, semaphore) for _key, text, voice in clips))
            pack = bytearray()
            ranges = {}
            for (key, _text, _voice), data in zip(clips, recordings):
                ranges[key] = [len(pack), len(data)]
                pack += data
            digest = hashlib.sha1(pack).hexdigest()[:8]
            filename = f"week-{week:02d}-{part}.{digest}.bin"
            (AUDIO_DIR / filename).write_bytes(pack)
            keep.add(filename)
            index[week][part] = {"file": filename, "clips": ranges}
    for stale in AUDIO_DIR.glob("week-*.bin"):
        if stale.name not in keep:
            stale.unlink()
    (AUDIO_DIR / "index.js").write_text(
        "// Generated by build_audio.py. Do not edit.\nwindow.MANDAYRIN_AUDIO = "
        + json.dumps(index, ensure_ascii=False, separators=(",", ":"))
        + ";\n",
        encoding="utf-8",
        newline="\n",
    )
    total = sum((AUDIO_DIR / name).stat().st_size for name in keep)
    print(f"Wrote {len(keep)} packs ({total / 1_000_000:.1f} MB) and audio/index.js")


if __name__ == "__main__":
    asyncio.run(main())
